dayname = int(input("enter any num (1 to 7) to check day name "))
if dayname == 1 :
    print("Today is monday ")
elif dayname == 2 :
    print("Today is tuesday ")
elif dayname == 3 :
    print("Today is wednesday ")
elif dayname == 4 :
    print("Today is thursday ")
elif dayname == 5 :
    print("Today is friday ")
elif dayname == 6 :
    print("Today is saturday ")
elif dayname == 7 :
    print("Today is sunday! ")
else :
    print("Invalid input  !")
